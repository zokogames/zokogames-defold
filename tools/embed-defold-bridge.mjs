#!/usr/bin/env node
// Embeds zokogames/web/zokogames_bridge.js into zokogames/bridge_js.lua so the Lua module can hand it
// to html5.run() without reading a resource file. Run after `node ../tools/sync-core.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const js = readFileSync(join(root, "zokogames/web/zokogames_bridge.js"), "utf8");
if (js.includes("]==]")) throw new Error("bridge contains ]==] which would end the Lua long string");
writeFileSync(
  join(root, "zokogames/bridge_js.lua"),
  `-- GENERATED by tools/embed-defold-bridge.mjs from zokogames/web/zokogames_bridge.js. Do not edit.\nreturn [==[\n${js}]==]\n`,
);
console.log("wrote zokogames/bridge_js.lua");
